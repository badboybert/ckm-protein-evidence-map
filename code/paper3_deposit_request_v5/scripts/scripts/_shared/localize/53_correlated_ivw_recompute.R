    # like everything else; a proxied row's variant is an ordinary panel variant that the instrument
    # map does not contain, so its panel name is taken from the cache instead of being looked up and
    # turned into NA. Both are already panel-space when ld_aligned() receives them, so it is called
    # with map = NULL and does not translate again.
    .src[, ld_panel := NA_character_]
    if (any(!.isprox)) {
      .dm <- if (length(.ldmap53)) setNames(names(.ldmap53), unname(.ldmap53)) else NULL
      .src$ld_panel[!.isprox] <- if (is.null(.dm)) .src$ld_name[!.isprox]
                                 else ld_names_to_panel(.src$ld_name[!.isprox], .dm)
    }
    if (any(.isprox))
      .src$ld_panel[.isprox] <- prox[match(paste(.src$SNP[.isprox], .src$ld_name[.isprox]),
                                           paste(prox$instrument, prox$proxy)), proxy_panel]
    if (any(is.na(.src$ld_panel))) {
      .note(g, oid, sprintf(paste0("%d row(s) have no reference-panel name for the variant their ",
                                   "outcome estimate came from"), sum(is.na(.src$ld_panel))),
            nrow(hk), NA_integer_, paste(.src$SNP[is.na(.src$ld_panel)], collapse = ", "))
      next
    }
    # ...aligned to the allele each estimate REPRESENTS. harmonise_data has already oriented every
    # beta.outcome to effect_allele.exposure, including the proxied rows (the extractor oriented the
    # proxy's beta onto the instrument's effect allele using PLINK's in-phase haplotype first). The
    # allele that carries that orientation ON THE PROXY is the in-phase one, so it, not the
    # instrument's letter, is what the panel row must be signed against.
    .src[, ld_ea := toupper(effect_allele.exposure)]
    if (any(.isprox)) {
      for (.i in which(.isprox)) {
        .pr <- prox[instrument == .src$SNP[.i] & proxy == .src$ld_name[.i]][1]
        .ie <- toupper(.src$effect_allele.exposure[.i])
        .inph <- if (!nrow(.pr) || is.na(.pr$a_hap1)) NA_character_
                 else if (.ie == toupper(.pr$a_hap1)) toupper(.pr$b_hap1)
                 else if (.ie == toupper(.pr$a_hap2)) toupper(.pr$b_hap2) else NA_character_
        .src$ld_ea[.i] <- .inph
      }
    }
    if (any(is.na(.src$ld_ea))) {
      .bad <- .src[is.na(ld_ea)]
      .note(g, oid, sprintf(paste0("%d proxied row(s) have no in-phase allele in the proxy cache, so ",
                                   "the panel row cannot be signed to the estimate it stands for"),
                            nrow(.bad)), nrow(hk), NA_integer_, paste(.bad$SNP, collapse = ", "))
      next
    }
    if (anyDuplicated(.src$ld_name)) {
      .note(g, oid, sprintf(paste0("two instrument rows resolve to the same outcome-source variant ",
                                   "(%s); their outcome estimates are not distinct observations"),
                            paste(unique(.src$ld_name[duplicated(.src$ld_name)]), collapse = ", ")),
            nrow(hk))
      next
    }
    ea <- setNames(.src$ld_ea, .src$ld_panel)
    .la <- ld_aligned(.src$ld_panel, ea, map = NULL)   # already panel-space; see ld_panel above
    if (is.null(.la$R)) { .note(g, oid, .la$reason, nrow(hk)); next }
    R <- .la$R
    # NOT a silent subset. Dropping instruments the panel does not know left the reported
    # correlated-IVW estimate resting on fewer instruments than the table beside it says, with
    # nothing recording the difference. It is reported per pair, and the number actually used is
    # carried out with the result.
    # Keyed on the OUTCOME-SOURCE name, which is what was queried. GC's rs79274569 and TGFBR3's
    # rs114776604 are genuinely absent from this panel, and that is the honest reason those cells
    # cannot be recomputed -- not "they used a proxy".
    .lost <- setdiff(.src$ld_panel, rownames(R))
    if (length(.lost)) {
      cat(sprintf("  [53] %s ~ %s: %d of %d outcome-source variant(s) absent from the LD panel (%s); "
                  , g, oid, length(.lost), nrow(.src), paste(utils::head(.lost, 3), collapse = ", ")),
          "the estimate below uses the remainder\n", sep = "")
      # RECORDED, not only printed. The reported estimate rests on fewer instruments than the table
      # beside it says, and a console line is not part of the artifact.
      .dropped[[length(.dropped) + 1L]] <- data.table(
        gene = g, outcome_id = oid, n_harmonised = nrow(.src), n_used = length(rownames(R)),
        dropped = paste(.lost, collapse = "|"),
        reason = "outcome-source variant(s) absent from the LD panel")
    }
    .keep <- .src$ld_panel %in% rownames(R)
    hk <- hk[.keep]; .src <- .src[.keep]
    R <- R[.src$ld_panel, .src$ld_panel, drop = FALSE]
    if (nrow(hk) < 2) {
      .note(g, oid, sprintf("%d instrument(s) remained after the LD panel, fewer than two",
                            nrow(hk)), nrow(hk)); next
    }
    bx <- hk$beta.exposure; bxse <- hk$se.exposure; by <- hk$beta.outcome; byse <- hk$se.outcome
    naive <- tryCatch(MendelianRandomization::mr_ivw(MendelianRandomization::mr_input(bx = bx, bxse = bxse, by = by, byse = byse), model = "fixed"), error = function(e) NULL)
    corr  <- tryCatch(MendelianRandomization::mr_ivw(MendelianRandomization::mr_input(bx = bx, bxse = bxse, by = by, byse = byse, correlation = R), model = "fixed"), error = function(e) NULL)
    # The third silent exit. An mr_ivw() that throws dropped the pair from the CSV with nothing
    # recording it -- indistinguishable from a pair that was never attempted.
    if (is.null(naive) || is.null(corr)) {
      .note(g, oid, sprintf("mr_ivw failed (%s)",
                            paste(c(if (is.null(naive)) "naive", if (is.null(corr)) "correlated"),
                                  collapse = " and ")), nrow(hk))
      next
    }
    # ...AND how many instruments it was computed over. `k` counts what survived the proxy and
    # LD-panel exclusions above, so p_recorded describes a different, larger set: 11 current
    # multi-instrument cells lose a proxied row, and for CNTNAP2-CKD the all-instrument p is 0.683945
    # against 0.747307 on the direct subset. Without both counts beside each other, part of the shift
    # from p_recorded to p_corr reads as an effect of LD correction when it is instrument removal.
    # (p_naive_fx is the like-for-like comparator: same subset, no correlation.)
    .rec <- mr_rec[gene == g & outcome_id == oid & method == "Inverse variance weighted"]
    p_rec <- .rec$pval[1]; k_rec <- .rec$n_snps[1]
    maxabsr <- max(abs(R[upper.tri(R)]))
    # THE ESTIMATES, not only the p-values. Both were computed and thrown away, so a correlated-IVW
    # row could only be read beside the ordinary-IVW beta recorded elsewhere -- a different number:
    # PAM-T2D is -0.0870568 unadjusted against -0.0921104 correlated, 5.8% apart. A p-value with no
    # effect size of its own also has no direction of its own.
    res[[length(res) + 1]] <- data.table(gene = g, outcome = names(OUTCOMES)[match(oid, OUTCOMES)],
      k = nrow(hk), k_recorded = k_rec, maxabsr = round(maxabsr, 6),
      p_recorded = p_rec, p_naive_fx = naive@Pvalue,
      p_corr = corr@Pvalue, se_ratio = corr@StdError / naive@StdError,
      beta_naive_fx = naive@Estimate, se_naive_fx = naive@StdError,
      beta_corr = corr@Estimate, se_corr = corr@StdError,
      class_corr = cls(corr@Pvalue), class_recorded = cls(p_rec))
  }
}
out <- rbindlist(res, fill = TRUE)[order(gene, outcome)]
# The generation these estimates belong to, IN the CSV -- a csv carries no attributes, so without a
# column an old correlated-IVW estimate can sit beside a rebuilt-generation protein-disease pair and
# nothing distinguishes them. The same hash the input gate above checked, so the two cannot disagree.
out[, `:=`(ckm_phase1_file = PHASE1_INSTRUMENTS, ckm_phase1_md5 = .inst_md5)]
of <- file.path(REPRO, "pam_conditional", "correlated_ivw_FULL_recompute.csv")
dir.create(dirname(of), showWarnings = FALSE, recursive = TRUE)
fwrite(out, of)

# THE OMISSION AUDIT GOES WITH THE RESULT IT EXPLAINS, before anything fallible runs. It used
# to be written at the very end, after a comparison against correlated_ivw_FULL.csv that reads a
# separate file -- so if that file was absent or malformed the script aborted with a SMALLER main
# result already published and no record of what had been dropped, which is the opposite of the
# claim that every omission is written beside it.
# Beside the result it explains, and REMOVED when there is nothing to report -- left behind from a
# previous run it would describe omissions this run did not have.
.dropf <- file.path(REPRO, "pam_conditional", "correlated_ivw_instruments_dropped.csv")
dir.create(dirname(.dropf), showWarnings = FALSE, recursive = TRUE)
if (!length(.dropped)) {
  unlink(.dropf)
  cat("\n[53] every attempted pair produced a row; no omission file written\n")
}
if (length(.dropped)) {
  .dd <- rbindlist(.dropped, fill = TRUE)
  fwrite(.dd, .dropf)
  cat(sprintf("\n[53] %d pair(s) produced no row or used fewer instruments than were harmonised; ",
              nrow(.dd)), "see ", .dropf, "\n", sep = "")
  print(.dd[, .N, by = reason][order(-N)])
}
cat(sprintf("\nrecomputed pairs: %d  -> %s\n", nrow(out), of))

if (!.has_prior) {
  # FIRST RUN ON THIS GENERATION: publish the canonical FULL, verified byte-for-byte.
  if (!isTRUE(file.copy(of, .fullf, overwrite = FALSE)))
    stop("53: could not publish ", .fullf)
  if (!identical(unname(tools::md5sum(of)), unname(tools::md5sum(.fullf))))
    stop("53: published FULL does not match the recompute output")
  cat("[53] published canonical:", .fullf, "\n")
} else {
# ---- compare to the prior run's canonical output ----
old <- fread(.fullf)
cat(sprintf("existing FULL rows: %d\n", nrow(old)))
m <- merge(old[, .(gene, outcome, p_corr_old = p_corr, se_ratio_old = se_ratio, class_old = class_corr)],
           out[, .(gene, outcome, p_corr, se_ratio, class_corr)], by = c("gene", "outcome"))
cat(sprintf("matched pairs: %d / %d\n", nrow(m), nrow(old)))
cat(sprintf("class agreement: %d / %d\n", sum(m$class_old == m$class_corr, na.rm = TRUE), nrow(m)))
cat(sprintf("max |log10(p_corr) - log10(p_corr_old)|: %.3f\n", max(abs(log10(m$p_corr) - log10(m$p_corr_old)), na.rm = TRUE)))
cat("\n-- significant-under-either (anchor: PAM-T2D, TSPAN8-T2D) --\n")
print(out[p_recorded < BONF | p_corr < BONF, .(gene, outcome, p_recorded = signif(p_recorded,3), p_corr = signif(p_corr,3), se_ratio = round(se_ratio,2))])
# What did NOT make it into `out`, written beside it. A pair that failed harmonisation, LD or either
# IVW simply became NULL and was skipped, so the table had fewer rows than pairs attempted with
# nothing recording which or why -- and a namespace error affecting one pair looked identical to a
# pair that legitimately had too few instruments.

cat("\n-- high-r anchors (doc: IDO1 .96, PAM .54, TNF .53, RET .28, NOTCH2 .27) --\n")
print(out[maxabsr >= 0.2, .(gene, outcome, maxabsr, se_ratio = round(se_ratio,2))][order(-maxabsr)][1:8])

# PUBLICATION NO LONGER DEPENDS ON THE ABSENCE OF A PRIOR RUN. The comparison above was built as a
# self-consistency check against an earlier run of the SAME computation, and publishing only when no
# prior existed was sound while that held. It stopped holding when the harmonisation changed: proxy
# rows now go through action = 1 rather than being dropped by action = 2, so a file left in place by an
# earlier run is the OLD method's answer -- and the report builders read `correlated_ivw_FULL.csv`, not
# the `_recompute` beside it. Measured on the current tree: five CNTNAP2-FinnGen cells differ, with
# CNTNAP2-HF at p_corr 0.0215538 stale against 0.00428120 recomputed and k 2 -> 3.
# The prior is kept as a dated copy rather than overwritten in place, so the change is inspectable.
.prev <- paste0(.fullf, ".prev_", format(file.mtime(.fullf), "%Y%m%dT%H%M%S"))
if (!file.exists(.prev) && !isTRUE(file.copy(.fullf, .prev, overwrite = FALSE)))
  stop("53: could not set aside the prior canonical FULL as ", .prev)
if (!isTRUE(file.copy(of, .fullf, overwrite = TRUE)))
  stop("53: could not publish ", .fullf)
if (!identical(unname(tools::md5sum(of)), unname(tools::md5sum(.fullf))))
  stop("53: published FULL does not match the recompute output")
cat("[53] published canonical:", .fullf, "\n     prior kept at:", .prev, "\n")
}

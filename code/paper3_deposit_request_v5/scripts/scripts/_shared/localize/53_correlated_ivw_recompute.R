.note <- function(g, oid, reason, n_h = NA_integer_, n_u = 0L, drop = NA_character_)
  .dropped[[length(.dropped) + 1L]] <<- data.table(
    gene = g, outcome_id = if (is.null(oid)) NA_character_ else oid,
    n_harmonised = n_h, n_used = n_u, dropped = drop, reason = reason)

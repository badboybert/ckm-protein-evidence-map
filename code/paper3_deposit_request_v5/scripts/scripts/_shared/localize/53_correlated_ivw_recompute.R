# THE FDR CUTOFF, DERIVED FROM THIS MR TABLE, ON THE HEADLINE'S OWN BH FAMILY.
#
# This script is a sensitivity analysis of the ESTIMATOR (ordinary IVW -> LD-aware correlated IVW).
# One thing may vary at a time: if the multiple-testing procedure moved too, a row falling from "FDR"
# to "ns" could not be attributed to the LD correction rather than to the threshold, and the table
# would answer no question. So the procedure is pinned to the primary one config documents as the
# headline -- BH once over the full N_PROTEINS_CANONICAL x outcomes grid with untested cells padded
# to p = 1 -- and the LD correction is left as the only moving part.
#
# It is DERIVED, not frozen. The constant here was FDR_P <- 1.088e-3, which matched neither family
# computable from this table (analysable-only 1.0097e-3, padded grid 8.1639e-4): a fourth,
# undocumented FDR surface, 33% looser than the headline cutoff -- so it labelled rows "FDR" that the
# headline rule calls "ns" -- and traceable to no run anyone can now name. config:141-160 states that
# three surfaces exist and must never be merged; a fourth one shipping inside a supplementary table
# is the failure that rule exists to prevent.

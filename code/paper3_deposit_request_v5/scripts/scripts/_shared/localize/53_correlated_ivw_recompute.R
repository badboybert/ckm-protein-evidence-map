    # than the estimate it re-estimates, which is the one thing it must not do. Discovery sets
    # eaf.outcome to NA and sends proxies through action = 1, which still refuses incompatible alleles
    # but does not adjudicate by frequency. The block below already knows about proxied rows (it takes
    # rho between the outcome-SOURCE variants); this makes them survive to reach it.
    .od      <- as.data.frame(od)
    .is_prox <- if ("proxy.outcome" %in% names(.od)) !is.na(.od$proxy.outcome) & .od$proxy.outcome else rep(FALSE, nrow(.od))
    # THE EXCEPTION IS KEPT AND ACTED ON (p567fix_r1 #2): with error -> NULL alone, a thrown arm was

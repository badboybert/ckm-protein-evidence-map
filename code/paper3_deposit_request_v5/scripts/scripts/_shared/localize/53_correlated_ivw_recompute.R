# `map` translates SNP-space names to the panel's for the ld_matrix call and back again for the
# returned dimnames, so the matrix this returns is indexed the way the caller's table is.
# Returns list(R = <matrix or NULL>, reason = <character or NA>). NOT a bare NULL, and NOT
# structure(NULL, ...): that is deprecated and, worse, returns a zero-length LIST -- is.null() on it
# is FALSE, so every guard written against it would have fallen through to rownames() on a list.
ld_aligned <- function(snps, ea, map = NULL) {
  .no <- function(why) list(R = NULL, reason = why)
  if (length(snps) < 2) return(.no("fewer than two instruments"))
  # ld_names_to_panel(), NOT ld_names_to_snp() with an inverted map. The pass-through that is right
  # for an unknown PROXY is wrong here: a name the panel does not have must mean "do not query",
  # otherwise the string is sent to the panel anyway and any record that happens to carry it is
  # accepted without rechecking position or alleles.
  # `length(map) == 0` is not the same as "legacy". A table that HAS rsid_ld_panel but whose values
  # are all missing produces an empty map, and the else-branch then queried the panel with
  # outcome-space names -- exactly the pass-through the comment above calls unsafe. The two cases
  # are distinguished by the caller, which passes NULL for a legacy table and a (possibly empty)
  # map for a new one.
  q <- if (is.null(map)) snps else ld_names_to_panel(snps, setNames(names(map), unname(map)))
  # The REASON travels with the NULL. `.unq` was computed and then never used, and every failure
  # here returned a bare NULL that the caller turned into `next` -- before the drop audit was
  # written -- so a pair could vanish from the output while the comments claimed every omission was
  # recorded.
  # The rs-format requirement belongs to the PANEL name, which is what the BIM carries, so it is
  # applied after the map rather than before it. Applied to the outcome-space name it discarded
  # instruments that have a perfectly good panel rsID: they were never queried and the pair lost
  # them without appearing in the drop audit.
  q[!is.na(q) & !grepl("^rs[0-9]+$", q)] <- NA_character_
  .unq <- snps[is.na(q)]
  q <- q[!is.na(q)]
  if (length(q) < 2)
    return(.no(sprintf("%d of %d instrument(s) are not in the LD panel, leaving fewer than two: %s",
                       length(.unq), length(snps), paste(utils::head(.unq, 4), collapse = ", "))))
  .err <- NA_character_
  R <- tryCatch(ieugwasr::ld_matrix(q, bfile = file.path(LD_EUR_DIR, "EUR"), plink_bin = PLINK_BIN, with_alleles = TRUE),
                error = function(e) { .err <<- conditionMessage(e); NULL })
  if (is.null(R))
    return(.no(paste0("ld_matrix failed: ", if (is.na(.err)) "no matrix returned" else .err)))
  if (nrow(R) < 2)
    return(.no(sprintf("the panel returned %d row(s), fewer than two", nrow(R))))
  rn <- rownames(R); base <- sub("_[A-Za-z]+_[A-Za-z]+$", "", rn); a1 <- sub("^[^_]+_([A-Za-z]+)_[A-Za-z]+$", "\\1", rn)
  if (length(map)) base <- ld_names_to_snp(base, map)                  # panel name -> SNP
  names(ea) -> nm  # ea is named by snp
  # -1 means "the panel's allele1 is the exposure's OTHER allele", and that has to be true, not
  # assumed. Written as a bare else-branch, any mismatch became a sign flip: a panel identifier
  # translated to the wrong SNP, or a row whose alleles disagree with the BIM record, produced a
  # signed correlation matrix for a different variant and a changed estimate with no error.
  a2 <- sub("^[^_]+_[A-Za-z]+_([A-Za-z]+)$", "\\1", rn)
  .eaU <- toupper(ea[base]); .a1U <- toupper(a1); .a2U <- toupper(a2)
  .bad <- which(.a1U != .eaU & .a2U != .eaU)
  if (length(.bad))
    return(.no(sprintf(paste0("%d variant(s) carry neither of the panel's alleles as their exposure ",
                              "effect allele, so the sign of their correlation cannot be established ",
                              "(e.g. %s: panel %s/%s, exposure effect %s)"),
                       length(.bad), base[.bad[1]], .a1U[.bad[1]], .a2U[.bad[1]], .eaU[.bad[1]])))
  flip <- ifelse(.a1U == .eaU, 1, -1)   # +1 if LD allele1 == exposure effect allele
  R <- diag(flip) %*% R %*% diag(flip)
  rownames(R) <- colnames(R) <- base
  list(R = R, reason = NA_character_)
}


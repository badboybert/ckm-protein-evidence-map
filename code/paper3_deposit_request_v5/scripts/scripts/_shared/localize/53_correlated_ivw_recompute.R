    if (nrow(.pd)) .pd$eaf.outcome <- NA_real_
    .proxy   <- .hz(.pd, 1L)
    if (!is.null(.e_harm)) { .note(g, oid, paste("harmonise_data THREW on one arm:", .e_harm)); next }
    harm <- if (is.null(.direct)) .proxy else if (is.null(.proxy)) .direct else
              as.data.frame(data.table::rbindlist(list(.direct, .proxy), fill = TRUE))
    if (is.null(harm)) { .note(g, oid, "harmonise_data produced no rows on either arm"); next }
    hk <- as.data.table(harm)[mr_keep == TRUE]
    if (nrow(hk) < 2) { .note(g, oid, sprintf("%d instrument(s) survived harmonisation, fewer than two",
                                              nrow(hk)), nrow(hk)); next }

    # instruments while being presented as the recomputation of a three-instrument result.
    #
    # proxy_r2.outcome is NOT an entry in this matrix. It documents the substitution; the
    # correlations are queried between the actual outcome-source variants.
    .src <- copy(hk)
    .isprox <- if ("proxy.outcome" %in% names(.src)) .src$proxy.outcome %in% TRUE else rep(FALSE, nrow(.src))
    .src[, ld_name := ifelse(.isprox, as.character(proxy_snp.outcome), as.character(SNP))]

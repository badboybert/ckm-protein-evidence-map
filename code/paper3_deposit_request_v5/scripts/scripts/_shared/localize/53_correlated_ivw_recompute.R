    # carries the INSTRUMENT's identifier but the PROXY's outcome beta, and correlated IVW's Omega is
    # SE_Yi SE_Yj rho_ij -- a covariance between the OUTCOME association estimates. So rho must be
    # taken between the outcome-source variants: the index variant for a direct row, the proxy for a
    # substituted one. Deleting the proxied rows instead, as this did, silently turned an estimator

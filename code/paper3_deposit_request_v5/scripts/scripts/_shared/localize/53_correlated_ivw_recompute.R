  pdt <- inst[gene == g]
  exp_fmt <- tryCatch(format_data(as.data.frame(pdt), type = "exposure", snp_col = "SNP", beta_col = "beta",
              se_col = "se", effect_allele_col = "effect_allele", other_allele_col = "other_allele",
              eaf_col = "eaf", pval_col = "pval", samplesize_col = "samplesize", phenotype_col = "exposure"),
              error = function(e) NULL)
  if (is.null(exp_fmt)) { .note(g, NULL, "format_data failed for this gene (all outcomes)"); next }
  for (oid in oids) {
    od <- out_all[id.outcome == oid & SNP %in% pdt$SNP]
    if (nrow(od) < 2) {
      .note(g, oid, sprintf(paste0("%d of this gene's %d instrument(s) have a row in the outcome ",

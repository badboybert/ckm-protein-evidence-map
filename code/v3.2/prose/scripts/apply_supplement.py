    # 5d. cross-references to Additional file 1's tables (PASS A FIX ROUND, 2026-10-01, m9). This document is Additional
    #     file 2, and two of its paragraphs (a figure legend citing Table S11, the S12 introduction citing Table S10)
    #     named tables it does not hold as 'Supplementary Table SN'. They print the journal form now, through the
    #     declared map (addfiles.cross_file_form); the inventory entries (the tables' own titles), the inventory sentence
    #     that says where those tables are, and every citation of this file's own Table S12 and figures are untouched.
    print("")
    print("== cross-references to Additional file 1's tables ==")
    n_x = 0
    for p in doc.paragraphs:
        t = para_text(p)
        if re.match(r"^Supplementary Table S\d+\s+—", norm(t)) or _af.SUPP_TABLES_NEW in t:
            continue
        ed = []
        for m in _af.LEGACY_RX.finditer(t):
            new = _af.cross_file_form(m.group(0), 2)
            if new != m.group(0):
                ed.append((m.start(), m.end(), new))
        if ed:
            splice(p, ed)
            n_x += len(ed)
            for s, e, new in ed:
                print("  %s  (%s)" % (new, norm(t)[:60]))
    left = [m.group(0) for p in doc.paragraphs
            if not re.match(r"^Supplementary Table S\d+\s+—", norm(para_text(p))) and _af.SUPP_TABLES_NEW not in para_text(p)
            for m in _af.LEGACY_RX.finditer(para_text(p)) if _af.cross_file_form(m.group(0), 2) != m.group(0)]
    if left:
        raise Refuse("cross-file table references survive in the legacy form: %s" % left[:3])
    print("  %d cross-file table reference(s) now name Additional file 1" % n_x)

    # 5b. print geometry: every figure title kept with its image, and no image taller than its section's text block
    fit = fit_figures(doc)
    print("  figure geometry: %d titles kept with their image; %d image(s) scaled into their section (%s)"
          % (fit["kept"], len(fit["scaled"]), ", ".join(fit["scaled"]) or "none"))

    # 6. closing assertion
    got = inventory(doc)
    if got != END_INVENTORY:
        raise Refuse("ending inventory is %s\nexpected                %s" % (got, END_INVENTORY))
    print("\nending inventory verified: %s" % ", ".join(got))

    if dry:
        print("\n--dry-run: not saving")
        return 0
    doc.save(out)
    print("wrote %s" % out)
    return 0



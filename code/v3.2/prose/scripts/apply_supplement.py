TITLE_ALLOWANCE_EMU = 914400          # 1 in: the title (one or two lines) plus both paragraphs' spacing. 0.5 in left
#                                       S7/S14/S19 at 415 pt in a 451 pt landscape block and Word still split title and image


def section_geometry(doc):
    """[(paragraph element, usable width EMU, usable height EMU)] for every body paragraph, from the sectPr that
    governs it (the next paragraph-level sectPr at or after it, else the body's final sectPr)."""
    from docx.oxml.ns import qn
    body = doc.element.body

    def usable(sp):
        sz, mar = sp.find(qn("w:pgSz")), sp.find(qn("w:pgMar"))
        g = lambda el, k: int(el.get(qn("w:" + k)))
        return ((g(sz, "w") - g(mar, "left") - g(mar, "right")) * 635, (g(sz, "h") - g(mar, "top") - g(mar, "bottom")) * 635)
    out, pending = [], []
    for el in body.iterchildren():
        if el.tag == qn("w:p"):
            pending.append(el)
            sp = el.find(qn("w:pPr") + "/" + qn("w:sectPr"))
            if sp is not None:
                w, h = usable(sp)
                out += [(x, w, h) for x in pending]
                pending = []
        elif el.tag == qn("w:sectPr"):
            w, h = usable(el)
            out += [(x, w, h) for x in pending]
            pending = []
    return out


def fit_figures(doc, apply=True):
    """Fix-round-3 Word render (2026-09-26): S7, S14 and S19 were taller than the 6.27 in landscape text block, so each
    title sat alone on one page and its image overflowed the bottom margin of the next. Every figure title is now kept
    with its image, and an image taller than (text height - one title line) or wider than the text is scaled down,
    aspect kept. With apply=False this only REPORTS (the gate's reader)."""
    from docx.oxml.ns import qn
    from docx.text.paragraph import Paragraph
    geo = section_geometry(doc)
    idx = {id(e): i for i, (e, _, _) in enumerate(geo)}
    res = dict(kept=0, scaled=[], unkept=[], oversize=[])
    for i, (el, w, h) in enumerate(geo):
        m = re.match(r"Supplementary Figure (S\d+[a-c]?)\.", norm(para_text(Paragraph(el, doc._body))))
        if not m or i + 1 >= len(geo):
            continue
        img = geo[i + 1][0]
        ext = img.findall(".//" + qn("wp:extent"))
        if len(ext) != 1:
            continue
        par = Paragraph(el, doc._body)
        if apply:
            par.paragraph_format.keep_with_next = True
        if par.paragraph_format.keep_with_next:
            res["kept"] += 1
        else:
            res["unkept"].append(m.group(1))
        cx, cy = int(ext[0].get("cx")), int(ext[0].get("cy"))
        cap_h, cap_w = geo[i + 1][2] - TITLE_ALLOWANCE_EMU, geo[i + 1][1]
        f = min(1.0, cap_h / float(cy), cap_w / float(cx))
        if f < 1.0:
            if not apply:
                res["oversize"].append("%s %.2f x %.2f in" % (m.group(1), cx / 914400.0, cy / 914400.0))
                continue
            nx, ny = int(cx * f), int(cy * f)
            for node in [ext[0]] + img.findall(".//" + qn("a:ext")):
                if node.get("cx") == str(cx) and node.get("cy") == str(cy):
                    node.set("cx", str(nx))
                    node.set("cy", str(ny))
            res["scaled"].append("%s %.2f -> %.2f in tall" % (m.group(1), cy / 914400.0, ny / 914400.0))
    return res


def inventory(doc):
    out = []
    for p in doc.paragraphs:
        m = re.match(r"Supplementary Figure (S\d+[a-c]?)\.", norm(para_text(p)))
        if m:
            out.append(m.group(1))
    return out


def block_of(doc, label):
    """Return (heading, image_or_None, caption_or_None) for a supplementary figure."""
    ps = doc.paragraphs
    hi = None
    for i, p in enumerate(ps):
        if norm(para_text(p)).startswith("Supplementary Figure %s." % label):
            if hi is not None:
                raise Refuse("heading for %s is not unique" % label)
            hi = i
    if hi is None:
        raise Refuse("no heading for %s" % label)
    img = cap = None
    for j in range(hi + 1, min(hi + 5, len(ps))):
        if has_drawing(ps[j]):
            img = ps[j]
        elif norm(para_text(ps[j])) and cap is None and img is not None:
            cap = ps[j]
            break
        elif norm(para_text(ps[j])).startswith("Supplementary Figure S"):
            break
    return ps[hi], img, cap


def unique_sub(doc, old, new):
    hits = []
    for p in doc.paragraphs:
        t = para_text(p)
        for m in re.finditer(re.escape(old), t):
            hits.append((p, m.start(), m.end()))
    if len(hits) == 0:
        raise Refuse("target not present: %r" % old[:70])
    if len(hits) > 1:
        raise Refuse("target occurs %d times, not unique: %r" % (len(hits), old[:70]))
    p, s, e = hits[0]
    splice(p, [(s, e, new)])



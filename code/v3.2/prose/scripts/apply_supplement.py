def check_s13_s14(text, root):
    """Every count the S13/S14 sentences print, re-derived from the named files with this module's own reading (an
    independent implementation of l2l4_facts' counts). [] = clean."""
    import csv as _csv
    rd = lambda k: list(_csv.DictReader(io.open(os.path.join(root, NEW_TABLE_FILES[k].replace("/", os.sep)),
                                                 encoding="utf-8-sig", newline="")))
    s23, br, cs = rd("S23_native_census__source.csv"), rd("bridge_screen_results.csv"), rd("bridge_class_summary.csv")
    net = [r for r in s23 if r["set"] == "census_network"]
    pil = [r for r in s23 if r["set"] == "pilot_offnetwork"]
    testable = [r for r in net if not r["eas_call"].startswith("NOT_TESTABLE")]
    keys = [(r["protein"], r["metabolite"]) for r in br]
    tested = [r for r in br if r["H4"] not in ("", "NA")]
    want = [
        "the %d network pairs, %d of them testable, and %d off-network pilot pairs" % (len(net), len(testable), len(pil)),
        "%d pairs over %d network proteins and %d metabolites" % (len(br), len({r["protein"] for r in br}),
                                                                    len({r["metabolite"] for r in br})),
        "%d meet the colocalization rule" % sum(1 for r in br if r["support"] == "True"),
        "for the %d bridges" % sum(1 for r in br if r["support"] == "True"),
        "the number of the %s rule variants" % (lambda c: c.pop() if len(c) == 1 else "?")({r["n_cells"] for r in cs}),
    ]
    bad = ["S13/S14 text lacks %r" % w for w in want if w not in text]
    if len(set(keys)) != len(keys):
        bad.append("bridge_screen_results.csv repeats a (protein, metabolite) pair")
    if len(tested) != len(br):
        bad.append("bridge_screen_results.csv has %d untested rows, but S14 says every pair was tested" % (len(br) - len(tested)))
    if len(s23) != len(net) + len(pil):
        bad.append("S23_native_census__source.csv carries a set other than census_network / pilot_offnetwork")
    # prose FIX round 5: 'The per-signal table gives, for the same pairs' -- its (locus, protein, metabolite) set IS the
    # class table's, and its primary counts are the class table's (the sensitivity leaves the registered classes unchanged)
    ps = rd("bridge_persignal_sensitivity.csv")
    k3 = lambda rows: sorted((r["locus"], r["protein"], r["metabolite"]) for r in rows)
    if k3(ps) != k3(cs) or len(set(k3(ps))) != len(ps):
        bad.append("bridge_persignal_sensitivity.csv does not hold exactly the class table's pairs")
    cmap = {(r["locus"], r["protein"], r["metabolite"]): r for r in cs}
    if any(r["primary_n_gene_attributed_ens116pc"] != cmap.get((r["locus"], r["protein"], r["metabolite"]), {}).get("n_gene_attributed")
           for r in ps):
        bad.append("bridge_persignal_sensitivity.csv's primary counts are not the class table's")
    if "The per-signal table gives, for the same pairs" not in text:
        bad.append("S14 text lacks the per-signal table's description")
    return bad


